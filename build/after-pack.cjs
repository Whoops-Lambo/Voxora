const fs = require("node:fs/promises");
const path = require("node:path");
// Generate an exact file manifest: uninstall never recursively deletes a user-chosen directory.
module.exports = async (context) => {
  if (context.electronPlatformName !== "win32") return;
  await fs.writeFile(path.join(context.appOutDir, "resources", "voxora-release.json"), JSON.stringify({ version: context.packager.appInfo.version }));
  const files = [],
    directories = [];
  async function walk(relative = "") {
    for (const entry of await fs.readdir(
      path.join(context.appOutDir, relative),
      { withFileTypes: true },
    )) {
      const name = path.join(relative, entry.name);
      if (entry.isDirectory()) {
        directories.push(name);
        await walk(name);
      } else if (entry.isFile()) files.push(name);
      else throw new Error(`Unsupported packaged file: ${name}`);
    }
  }
  await walk();
  const escape = (s) => s.replaceAll("$", "$$").replaceAll('"', '$\\"');
  const win = (s) => escape(s.split(path.sep).join("\\"));
  const lines = [
    "; Generated by after-pack.cjs; do not edit.",
    "!macro VoxoraInstallFiles",
  ];
  for (const file of files.sort()) {
    const dir = path.dirname(file);
    lines.push(`SetOutPath "$INSTDIR${dir === "." ? "" : "\\" + win(dir)}"`);
    lines.push(
      `File "${escape(path.join(context.appOutDir, file).replaceAll("\\", "/"))}"`,
      'IfErrors 0 +3',
      'SetErrorLevel 2',
      'Abort "Voxora files could not be replaced. Close Voxora and run the installer again."',
    );
  }
  lines.push("!macroend", "!macro VoxoraUninstallFiles");
  for (const file of files) lines.push(`Delete "$INSTDIR\\${win(file)}"`);
  for (const dir of directories.sort(
    (a, b) => b.split(path.sep).length - a.split(path.sep).length,
  ))
    lines.push(`RMDir "$INSTDIR\\${win(dir)}"`);
  lines.push("!macroend", "");
  await fs.writeFile(
    path.join(context.packager.projectDir, "build", "files.generated.nsh"),
    lines.join("\n"),
  );
};
