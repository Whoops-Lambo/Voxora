import test from 'node:test';
import assert from 'node:assert/strict';
import {fixture} from './support/server.mjs';
import {planTemplate} from '../bot-templates.js';
const fail=(status,message)=>{throw Object.assign(Error(message),{status});};
test('bot planners isolate state, enforce music ownership, validate links and keep tasks channel scoped',()=>{
 const base={server:{people:[{id:'a',username:'alice'},{id:'b',username:'bob'}]},user:{id:'a'},channel:'one',args:'',fail,now:100000000};
 const original={accounts:{a:{balance:250,lastDaily:0,inventory:[]}}};
 const paid=planTemplate({...base,template:'economy',data:original,command:'pay',args:'@bob 100'});
 assert.equal(original.accounts.a.balance,250);assert.equal(paid.next.accounts.a.balance,150);assert.equal(paid.next.accounts.b.balance,100);
 assert.throws(()=>planTemplate({...base,template:'economy',data:original,command:'pay',args:'@bob -1'}));
 for(const url of ['http://example.com','https://user:pass@example.com','javascript:alert(1)'])assert.throws(()=>planTemplate({...base,template:'music',command:'play',args:url}));
 const music=planTemplate({...base,template:'music',command:'play',args:'https://example.com/song | Song'});
 assert.throws(()=>planTemplate({...base,user:{id:'b'},template:'music',data:music.next,command:'skip'}),e=>e.status===403);
 assert.equal(planTemplate({...base,user:{id:'b'},canDJ:true,template:'music',data:music.next,command:'skip'}).next.queues.one.length,0);
 const task=planTemplate({...base,template:'tasks',command:'todo',args:'Prepare event'});
 assert.match(planTemplate({...base,template:'tasks',data:task.next,command:'tasks'}).text,/Prepare event/);
 assert.doesNotMatch(planTemplate({...base,channel:'two',template:'tasks',data:task.next,command:'tasks'}).text,/Prepare event/);
});
test('installed templates execute, serialize credits, persist, respect scopes, DJ roles and archives',{timeout:60000},async()=>{
 const f=await fixture();
 try{
  const owner=await f.register('template_owner'),member=await f.register('template_member'),staff=await f.register('template_staff');
  const O=(p,m,d)=>f.call(owner,p,m,d),U=(p,m,d)=>f.call(member,p,m,d),S=(p,m,d)=>f.call(staff,p,m,d);
  const s=(await O('/servers','POST',{name:'Template Lab'})).data,base='/servers/'+s.id,channel=s.channels.find(c=>c.type==='text').id;
  for(const user of [member,staff])assert.equal((await f.call(user,'/invites/join','POST',{code:s.invite})).status,200);
  const catalog=(await O('/bot-catalog')).data;assert.ok(catalog.some(a=>a.id==='voxora-economy'));assert.equal(catalog.length,5);
  for(const applicationId of ['voxora-economy','voxora-music','voxora-games','voxora-tasks'])assert.equal((await O(base+'/bots','POST',{applicationId,channelIds:[channel]})).status,201);
  const command=(who,applicationId,name,args='',ch=channel)=>f.call(who,'/commands','POST',{channel:ch,applicationId,name,arguments:args});
  const claims=await Promise.all([command(member,'voxora-economy','daily'),command(member,'voxora-economy','daily')]);
  assert.deepEqual(claims.map(r=>r.status).sort(),[201,400]);
  assert.match((await command(member,'voxora-economy','balance')).data.response.text,/250/);
  assert.equal((await command(member,'voxora-economy','pay','@template_owner 100')).status,201);
  assert.match((await command(owner,'voxora-economy','balance')).data.response.text,/100/);
  assert.equal((await command(member,'voxora-economy','buy','diamond')).status,400);
  assert.equal((await command(member,'voxora-tasks','todo','Prepare launch')).status,201);
  assert.doesNotMatch((await command(owner,'voxora-tasks','tasks')).data.response.text,/Prepare launch/);
  assert.equal((await command(member,'voxora-music','play','https://example.com/song | Song')).status,201);
  assert.equal((await command(staff,'voxora-music','skip')).status,403);
  const dj=(await O(base+'/roles','POST',{name:'DJ',permissions:['manageMusicQueue']})).data;
  assert.equal((await O(base+'/members/'+staff.id,'PATCH',{roles:[dj.id]})).status,200);
  assert.equal((await command(staff,'voxora-music','skip')).status,201);
  assert.equal((await command(owner,'voxora-games','dice','2d6')).status,201);
  const manager=(await O(base+'/roles','POST',{name:'Delegated Manager',permissions:['manageBots','manageInvites','pinMessages','archiveChannels','bypassSlowmode']})).data;
  assert.equal((await O(base+'/members/'+staff.id,'PATCH',{roles:[manager.id]})).status,200);
  assert.equal((await S(base+'/bots')).status,200);
  const invitation=(await O(base+'/invites','POST',{})).data;
  assert.equal((await S(base+'/invites/'+invitation.code,'DELETE')).status,200);
  const msg=(await U('/messages','POST',{channel,text:'A message to pin'})).data;
  assert.equal((await S('/messages/'+msg.id+'/pin','POST',{})).status,200);
  assert.equal((await S('/messages/'+msg.id,'DELETE')).status,403);
  assert.equal((await O('/channels/'+channel,'PATCH',{slowmode:60})).status,200);
  for(const text of ['Bypass first','Bypass second'])assert.equal((await S('/messages','POST',{channel,text})).status,201);
  assert.equal((await U('/messages','POST',{channel,text:'Must wait'})).status,429);
  assert.equal((await O('/channels/'+channel,'PATCH',{slowmode:0})).status,200);
  assert.equal((await U('/channels/'+channel,'PATCH',{archived:true})).status,403);
  assert.equal((await S('/channels/'+channel,'PATCH',{archived:true,name:'not-allowed'})).status,400);
  assert.equal((await S('/channels/'+channel,'PATCH',{archived:true})).status,200);
  assert.equal((await command(owner,'voxora-economy','daily')).status,403);
  assert.equal((await O('/messages','POST',{channel,text:'Owner cannot post in archive'})).status,403);
  assert.equal((await S('/channels/'+channel,'PATCH',{archived:false})).status,200);
  const view=(await O('/state')).data.servers.find(x=>x.id===s.id);assert.ok(!('botTemplateData' in view));
  await f.stop();await f.start();
  assert.match((await command(member,'voxora-economy','balance')).data.response.text,/150/);
  assert.match((await command(member,'voxora-tasks','tasks')).data.response.text,/Prepare launch/);
  assert.equal((await S(base+'/bots/voxora-economy','PATCH',{enabled:false})).status,200);
  assert.equal((await command(member,'voxora-economy','balance')).status,403);
  const other=(await O(base+'/channels','POST',{name:'out-of-scope'})).data;
  assert.equal((await command(member,'voxora-games','coinflip','',other.id)).status,403);
 }finally{await f.cleanup();}
});
