import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { CommunityStore } from "../examples/community-state.mjs";
import { commands, handleCommand } from "../examples/community-commands.mjs";
import { fixture } from "./support/server.mjs";

test("community economy preserves balances, cooldowns, inventories and receipts across concurrent commands and restarts", async () => {
  const dir = await mkdtemp("/tmp/voxora-economy-");
  let store;
  const alice = { id: "alice", username: "alice", displayName: "Alice", bot: false }, bob = { id: "bob", username: "bob", displayName: "Bob", bot: false };
  const context = { server: { id: "one", name: "One" }, user: alice, members: [alice, bob] };
  let now = 1700000000000;
  const run = (name, args = "", id = randomUUID(), user = alice, server = "one") => handleCommand({ id, command: name, arguments: args, user }, { ...context, user, server: { id: server, name: server } }, store, now);
  try {
    store = await new CommunityStore(dir + "/state.json").open();
    await assert.rejects(new CommunityStore(dir + "/state.json").open(), /Another bot process/);
    assert.equal(commands.length, 25);
    const id = randomUUID();
    const duplicates = await Promise.all(Array.from({ length: 8 }, () => run("daily", "", id)));
    assert.ok(duplicates.every((r) => r.text === duplicates[0].text));
    assert.match((await run("balance")).text, /250 credits/);
    assert.match((await run("daily")).text, /again in/);
    assert.match((await run("work")).text, /earned/);
    assert.match((await run("work")).text, /again in/);
    assert.match((await run("pay", "@bob -10")).text, /Use \/pay/);
    assert.match((await run("pay", "@bob 1.5")).text, /Use \/pay/);
    assert.match((await run("pay", "@alice 10")).text, /another human/);
    assert.match((await run("pay", "@missing 10")).text, /Member not found/);
    const paymentId = randomUUID();
    await Promise.all(Array.from({ length: 5 }, () => run("pay", "@bob 100", paymentId)));
    assert.match((await run("balance", "@bob")).text, /100 credits/);
    const payments = await Promise.all(Array.from({ length: 8 }, () => run("pay", "@bob 100")));
    assert.ok(payments.some((r) => r.text.includes("not have enough")));
    const balances = await store.read((s) => Object.values(s.servers.one.accounts).map((a) => a.balance));
    assert.ok(balances.every((b) => Number.isSafeInteger(b) && b >= 0));
    assert.ok(balances.reduce((sum, b) => sum + b, 0) >= 275 && balances.reduce((sum, b) => sum + b, 0) <= 350);
    assert.match((await run("balance", "", randomUUID(), alice, "two")).text, /0 credits/);
    await run("daily", "", randomUUID(), bob);
    assert.match((await run("buy", "bronze", randomUUID(), bob)).text, /Bought/);
    assert.match((await run("buy", "bronze", randomUUID(), bob)).text, /already own/);
    assert.match((await run("inventory", "@bob")).text, /Bronze badge/);
    assert.match((await run("leaderboard")).text, /Alice/);
    await store.close();
    store = await new CommunityStore(dir + "/state.json").open();
    assert.match((await run("inventory", "@bob")).text, /Bronze badge/);
    assert.deepEqual(await run("daily", "", id), duplicates[0]);
    assert.match((await run("daily")).text, /again in/);
    now += 86400001;
    assert.match((await run("daily")).text, /earned/);
    for (const args of ["", "moderation", "economy", "utility"]) assert.ok((await run("bothelp", args)).text.length <= 2000);
    assert.match((await run("roll", "999d6")).text, /1–20/);
    assert.match((await run("choose", "one")).text, /2–20/);
    assert.deepEqual((await run("poll", "Game? | A | B")).poll.answers, ["A", "B"]);
  } finally { await store?.close(); await rm(dir, { recursive: true, force: true }); }
});

test("bot moderation checks both actors, hierarchy, scopes, replay receipts and persists private warnings", async () => {
  const f = await fixture();
  try {
    const owner = await f.register("community_owner"), member = await f.register("community_member"), target = await f.register("community_target");
    const O = (p, m, d) => f.call(owner, p, m, d);
    const s = (await O("/servers", "POST", { name: "Moderation" })).data, base = "/servers/" + s.id;
    const channel = s.channels[0].id;
    for (const u of [member, target]) await f.call(u, "/invites/join", "POST", { code: s.invite });
    const app = (await O("/applications", "POST", { name: "Community Bot" })).data;
    const B = (p, m, d) => f.call({ token: app.token }, "/bot" + p, m, d);
    await O(base + "/bots", "POST", { applicationId: app.application.id });
    await B("/commands", "PUT", { commands });
    const invoke = async (name, who = owner) => (await f.call(who, "/commands", "POST", { channel, name, applicationId: app.application.id })).data.interactionId;
    const action = (id, data) => B("/interactions/" + id + "/moderation", "POST", data);
    const warning = { action: "warn", targetId: target.id, reason: "Keep it civil" };
    assert.equal((await action(await invoke("warn"), warning)).status, 403);
    const role = (await O(base + "/roles", "POST", { name: "Bot moderator", permissions: ["moderateMembers", "kickMembers", "banMembers", "manageMessages"] })).data;
    await O(base + "/members/" + app.application.userId, "PATCH", { roles: [role.id] });
    assert.equal((await action(await invoke("warn", member), warning)).status, 403);
    assert.equal((await action(await invoke("warn"), { ...warning, targetId: owner.id })).status, 403);
    assert.equal((await action(await invoke("warn"), { ...warning, targetId: app.application.userId })).status, 403);
    const warningId = await invoke("warn");
    const repeated = await Promise.all([action(warningId, warning), action(warningId, warning)]);
    assert.ok(repeated.every((r) => r.status === 200 && r.data.count === 1));
    assert.equal((await action(warningId, { ...warning, reason: "Different" })).status, 409);
    const bootstrap = (await f.call(member, "/state")).data;
    assert.ok(!Object.hasOwn(bootstrap.servers.find((x) => x.id === s.id), "warnings"));
    const review = await action(await invoke("warnings"), { action: "warnings", targetId: target.id });
    assert.equal(review.data.warnings[0].requestedById, owner.id);
    assert.equal((await action(await invoke("timeout"), { action: "timeout", targetId: target.id, durationSeconds: 60 })).status, 200);
    assert.equal((await f.call(target, "/messages", "POST", { channel, text: "No" })).status, 403);
    assert.equal((await action(await invoke("untimeout"), { action: "untimeout", targetId: target.id })).status, 200);
    const post = (await O("/messages", "POST", { channel, text: "Keep pinned" })).data;
    await O("/messages/" + post.id + "/pin", "POST", {});
    await O("/messages", "POST", { channel, text: "Remove this" });
    const purge = await action(await invoke("purge"), { action: "purge", count: 1 });
    assert.equal(purge.data.count, 1);
    assert.ok((await O("/messages?channel=" + channel)).data.some((m) => m.id === post.id));
    const pending = await invoke("warn");
    await O(base + "/roles/" + role.id, "PATCH", { permissions: [] });
    assert.equal((await action(pending, warning)).status, 403);
    await O(base + "/roles/" + role.id, "PATCH", { permissions: ["moderateMembers", "kickMembers", "banMembers", "manageMessages"] });
    const kickId = await invoke("kick");
    const kick = { action: "kick", targetId: target.id };
    assert.equal((await action(kickId, kick)).status, 200);
    assert.equal((await action(kickId, kick)).status, 200);
    await f.call(target, "/invites/join", "POST", { code: s.invite });
    assert.equal((await action(await invoke("ban"), { action: "ban", targetId: target.id })).status, 200);
    assert.equal((await f.call(target, "/invites/join", "POST", { code: s.invite })).status, 403);
    const unbanId = await invoke("unban");
    assert.ok((await B("/interactions/" + unbanId + "/context")).data.bannedMembers.some((u) => u.id === target.id));
    assert.equal((await action(unbanId, { action: "unban", targetId: target.id })).status, 200);
    await f.call(target, "/invites/join", "POST", { code: s.invite });
    await f.stop(); await f.start();
    assert.equal((await action(await invoke("warnings"), { action: "warnings", targetId: target.id })).data.count, 1);
    assert.equal((await action(await invoke("clearwarns"), { action: "clearwarns", targetId: target.id })).data.count, 1);
    const scoped = await invoke("warn");
    await O(base + "/bots/" + app.application.id, "PATCH", { channelIds: [] });
    assert.equal((await action(scoped, warning)).status, 404);
    const audit = (await O(base + "/audit")).data;
    assert.ok(audit.some((a) => a.action === "Member warned" && a.requestedById === owner.id));
  } finally { await f.cleanup(); }
});
