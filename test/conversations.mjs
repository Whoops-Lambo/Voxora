test("threads inherit channel access, enforce moderation/slowmode and persist messages, reads and bot scopes", async () => {
  const f = await fixture();
  let sdk, connecting;
  try {
    const owner = await f.register("thread_owner"), member = await f.register("thread_member"), outsider = await f.register("thread_outside");
    const O = (p,m,d) => f.call(owner,p,m,d), M = (p,m,d) => f.call(member,p,m,d);
    const s = (await O("/servers","POST",{name:"Threads"})).data, base = "/servers/"+s.id, channel = s.channels[0].id;
    await M("/invites/join","POST",{code:s.invite});
    const root = (await O("/messages","POST",{channel,text:"Plan the release"})).data;
    const t = (await M("/threads","POST",{messageId:root.id,name:"Release plan"})).data;
    assert.ok(t.id); assert.equal((await f.call(outsider,"/threads/"+t.id)).status,404);
    assert.equal((await M("/threads","POST",{messageId:root.id,name:"Duplicate"})).status,200);
    const reply = (await M("/threads/"+t.id+"/messages","POST",{text:"First reply"})).data;
    assert.equal((await O("/threads/"+t.id)).data.unreadCount,1);
    assert.equal((await O("/threads/"+t.id+"/read","POST",{through:reply.sequence})).status,200);
    assert.equal((await O("/threads/"+t.id)).data.unreadCount,0);
    await O("/threads/"+t.id+"/read","POST",{through:0}); assert.equal((await O("/threads/"+t.id)).data.readSequence,reply.sequence);
    assert.equal((await O("/thread-messages/"+reply.id,"PATCH",{text:"Not mine"})).status,403);
    assert.equal((await M("/thread-messages/"+reply.id,"PATCH",{text:"Edited reply"})).status,200);
    await M("/thread-messages/"+reply.id+"/reactions","POST",{emoji:"✅"});
    assert.equal((await O("/messages?channel="+channel)).data[0].thread.replyCount,1);
    await M("/threads/"+t.id,"PATCH",{archived:true});
    assert.equal((await M("/threads/"+t.id+"/messages","POST",{text:"Closed"})).status,403);
    await M("/threads/"+t.id,"PATCH",{archived:false}); await O("/threads/"+t.id,"PATCH",{locked:true});
    assert.equal((await M("/threads/"+t.id,"PATCH",{archived:false})).status,403);
    assert.equal((await M("/thread-messages/"+reply.id+"/reactions","POST",{emoji:"✅"})).status,403);
    await O("/threads/"+t.id,"PATCH",{locked:false});
    await O("/channels/"+channel,"PATCH",{slowmode:60});
    assert.equal((await M("/threads/"+t.id+"/messages","POST",{text:"Slowmode"})).status,429);
    await O("/channels/"+channel,"PATCH",{slowmode:0});
    const app = (await O("/applications","POST",{name:"Thread Bot"})).data;
    await O(base+"/bots","POST",{applicationId:app.application.id});
    sdk = new VoxoraBot({url:f.origin,token:app.token});
    assert.equal((await sdk.getThreads(channel))[0].id,t.id);
    const events=[];
    for (const name of ["ready","threadMessage","threadMessageUpdate","threadMessageDelete","threadUpdate"]) sdk.on(name,(event)=>events.push({name,event}));
    connecting=sdk.connect();await until(()=>events.some((e)=>e.name==="ready"));
    const botReply = await sdk.sendThreadMessage(t.id,"From SDK"); assert.equal(botReply.bot,true);
    await sdk.editThreadMessage(botReply.id,"SDK edited"); await sdk.reactThreadMessage(reply.id,"👍");
    await until(()=>events.some((e)=>e.name==="threadMessage"&&e.event.id===botReply.id));
    await until(()=>events.some((e)=>e.name==="threadMessageUpdate"&&e.event.text==="SDK edited"));
    const temporary=await sdk.sendThreadMessage(t.id,"Temporary bot reply");await sdk.deleteThreadMessage(temporary.id);
    await until(()=>events.some((e)=>e.name==="threadMessageDelete"&&e.event.id===temporary.id));
    await until(()=>events.some((e)=>e.name==="threadUpdate"&&e.event.threadId===t.id));
    await O(base+"/bots/"+app.application.id,"PATCH",{channelIds:[]});
    await assert.rejects(sdk.getThreadMessages(t.id),(e)=>e.status===403);
    sdk.close();await connecting;
    await O("/channels/"+channel,"PATCH",{overwrites:[{type:"member",id:member.id,allow:[],deny:["viewChannel"]}]});
    assert.equal((await M("/threads/"+t.id+"/messages")).status,404);
    await O("/channels/"+channel,"PATCH",{overwrites:[]});
    await f.stop(); await f.start();
    assert.equal((await O("/threads/"+t.id)).data.replyCount,2);
    assert.ok((await O("/search?q=SDK%20edited")).data.some((m)=>m.threadId===t.id));
    for (let i=0;i<110;i++) assert.equal((await O("/threads/"+t.id+"/messages","POST",{text:"History reply "+i})).status,201);
    const latest=(await O("/threads/"+t.id+"/messages")).data;
    assert.equal(latest.messages.length,100);assert.equal(latest.hasOlder,true);
    const earlier=(await O("/threads/"+t.id+"/messages?before="+latest.messages[0].id)).data;
    assert.equal(earlier.messages.length,12);assert.equal(earlier.hasOlder,false);
    assert.equal(new Set([...earlier.messages,...latest.messages].map((m)=>m.id)).size,112);
    const around=(await O("/threads/"+t.id+"/messages?around="+reply.id)).data;
    assert.equal(around.messages[0].id,reply.id);assert.equal(around.hasNewer,true);
    assert.equal((await O("/threads/"+t.id)).data.readSequence,reply.sequence);
    await O("/messages/"+root.id,"DELETE");
    assert.equal((await M("/threads/"+t.id)).status,404);
    assert.equal((await O("/search?q=SDK%20edited")).data.length,0);
  } finally { sdk?.close();await connecting;await f.cleanup(); }
});

test("saved messages are personal live references with private notes and hide revoked, blocked or deleted content", async () => {
  const f = await fixture();
  try {
    const owner=await f.register("saved_owner"), member=await f.register("saved_member");
    const O=(p,m,d)=>f.call(owner,p,m,d), M=(p,m,d)=>f.call(member,p,m,d);
    const s=(await O("/servers","POST",{name:"Saved"})).data, channel=s.channels[0].id;
    await M("/invites/join","POST",{code:s.invite});
    const m=(await O("/messages","POST",{channel,text:"Useful reference"})).data;
    const bookmark=(await M("/saved-messages","POST",{messageId:m.id,note:"PERSONAL-NOTE"})).data;
    assert.equal((await O("/saved-messages")).data.total,0);
    assert.equal((await O("/saved-messages/"+bookmark.id,"PATCH",{note:"Not mine"})).status,404);
    assert.equal((await M("/saved-messages","POST",{messageId:m.id})).status,200);
    assert.equal((await M("/saved-messages?q=personal")).data.total,1);
    assert.ok(!JSON.stringify((await O("/state")).data.users).includes("PERSONAL-NOTE"));
    await O("/messages/"+m.id,"PATCH",{text:"Current edited text"});
    assert.equal((await M("/saved-messages")).data.items[0].message.text,"Current edited text");
    await O("/channels/"+channel,"PATCH",{overwrites:[{type:"member",id:member.id,allow:[],deny:["viewChannel"]}]});
    const hidden=(await M("/saved-messages")).data;
    assert.equal(hidden.total,0); assert.equal(hidden.unavailable.length,1); assert.ok(!JSON.stringify(hidden).includes("Current edited text"));
    await O("/channels/"+channel,"PATCH",{overwrites:[]});
    const t=(await O("/threads","POST",{messageId:m.id,name:"Saved replies"})).data;
    const reply=(await O("/threads/"+t.id+"/messages","POST",{text:"A threaded reference"})).data;
    await M("/saved-messages","POST",{messageId:reply.id,threadId:t.id});
    await f.stop(); await f.start(); assert.equal((await M("/saved-messages")).data.total,2);
    const dm=(await M("/conversations","POST",{userId:owner.id})).data;
    const direct=(await O("/messages","POST",{channel:dm.id,text:"Private direct reference"})).data;
    await M("/saved-messages","POST",{messageId:direct.id}); await M("/blocks/"+owner.id,"POST",{});
    assert.ok(!(await M("/saved-messages")).data.items.some((i)=>i.messageId===direct.id));
    await O("/messages/"+m.id,"DELETE");
    assert.equal((await M("/saved-messages")).data.total,0);
    await M("/saved-messages/unavailable","DELETE"); assert.equal((await M("/saved-messages")).data.unavailable.length,0);
  } finally { await f.cleanup(); }
});

test("custom emoji validate uploads, enforce roles and scope, support bots/reactions and preserve published assets", async () => {
  const f=await fixture();
  try {
    const owner=await f.register("emoji_owner"), member=await f.register("emoji_member"), follower=await f.register("emoji_follower");
    const O=(p,m,d)=>f.call(owner,p,m,d), M=(p,m,d)=>f.call(member,p,m,d), F=(p,m,d)=>f.call(follower,p,m,d);
    const s=(await O("/servers","POST",{name:"Emoji Lab"})).data, base="/servers/"+s.id, channel=s.channels[0].id;
    await M("/invites/join","POST",{code:s.invite});
    const upload=async(who,name,data=png)=> { const r=await fetch(f.origin+"/api"+base+"/emojis?name="+name,{method:"POST",headers:{Cookie:who.cookie,"Content-Type":"image/png"},body:data});return {status:r.status,data:await r.json()}; };
    assert.equal((await upload(member,"wave")).status,403);
    assert.equal((await upload(owner,"wave",Buffer.from('<svg onload="bad()"/>'))).status,400);
    assert.equal((await upload(owner,"wave",Buffer.alloc(256*1024+1))).status,413);
    const big=Buffer.from(png); big.writeUInt32BE(257,16); assert.equal((await upload(owner,"large",big)).status,400);
    const e=(await upload(owner,"wave")).data; assert.ok(e.id); assert.equal(e.mime,"image/png");
    assert.equal((await upload(owner,"WAVE")).status,409);
    assert.equal((await fetch(f.origin+e.url,{headers:{Cookie:follower.cookie}})).status,404);
    assert.deepEqual(Buffer.from(await(await fetch(f.origin+e.url,{headers:{Cookie:member.cookie}})).arrayBuffer()),png);
    const m=(await M("/messages","POST",{channel,text:"Hello "+e.code})).data;
    assert.equal(m.customEmojis[0].id,e.id); assert.equal((await M("/messages/"+m.id+"/reactions","POST",{emoji:e.code})).status,200);
    const target=(await F("/servers","POST",{name:"Emoji Followers"})).data;
    assert.equal((await F("/messages","POST",{channel:target.channels[0].id,text:e.code})).status,400);
    await O("/channels/"+channel,"PATCH",{announcement:true}); await F("/invites/join","POST",{code:s.invite});
    await F("/announcements/"+channel+"/follows","POST",{channelId:target.channels[0].id});
    assert.equal((await O("/messages/"+m.id+"/publish","POST",{})).data.delivered,1);
    const copy=(await F("/messages?channel="+target.channels[0].id)).data[0]; assert.ok(copy.customEmojis[0].url.startsWith("/api/files/"));
    await O(base+"/emojis/"+e.id,"PATCH",{name:"hello"});
    await M("/messages/"+m.id+"/reactions","POST",{emoji:e.code});
    assert.equal((await O("/messages?channel="+channel)).data.find((x)=>x.id===m.id).reactions.length,0);
    assert.equal((await M("/messages?channel="+channel)).data[0].customEmojis[0].name,"hello");
    await O(base+"/emojis/"+e.id,"DELETE");
    assert.equal((await M("/messages","POST",{channel,text:e.code})).status,400);
    assert.deepEqual(Buffer.from(await(await fetch(f.origin+copy.customEmojis[0].url,{headers:{Cookie:follower.cookie}})).arrayBuffer()),png);
    const role=(await O(base+"/roles","POST",{name:"Emoji Manager",permissions:["manageExpressions"]})).data;
    await O(base+"/members/"+member.id,"PATCH",{roles:[role.id]});
    let req; const waiting=new Promise((resolve,reject)=>{req=http.request(f.origin+"/api"+base+"/emojis?name=delayed",{method:"POST",headers:{Cookie:member.cookie}},res=>{res.resume();res.on("end",()=>resolve(res.statusCode));});req.on("error",reject);req.write(png.subarray(0,-1));});
    await O(base+"/roles/"+role.id,"PATCH",{permissions:[]}); req.end(png.subarray(-1)); assert.equal(await waiting,403);
    assert.equal((await O(base+"/emojis")).data.length,0);
    await f.stop(); await f.start(); assert.equal((await F("/messages?channel="+target.channels[0].id)).data[0].customEmojis.length,1);
  } finally { await f.cleanup(); }
});
