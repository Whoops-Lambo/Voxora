import {test,expect} from '@playwright/test';
test('role presets and custom templates can be applied and saved through Server Settings',async({page,request})=>{
  await page.goto('/app');
  await page.getByRole('button',{name:'Register',exact:true}).click();
  await page.getByLabel('DISPLAY NAME').fill('Template Owner');
  await page.getByLabel('USERNAME').fill('template_owner');
  await page.getByLabel('PASSWORD').fill('Fixture-password-482');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await expect(page.locator('#message-input')).toBeVisible();
  await page.getByRole('button',{name:'Add a Server',exact:true}).click();
  await page.getByRole('button',{name:'Create My Own',exact:true}).click();
  await page.getByLabel('SERVER NAME').fill('Template Lab');
  await page.getByRole('button',{name:'Create',exact:true}).click();
  await expect(page.locator('#sidebar-top')).toContainText('Template Lab');
  await page.locator('#sidebar-top .server-heading').click();
  await page.getByRole('button',{name:'Server Settings',exact:true}).click();
  await page.getByRole('button',{name:'Roles',exact:true}).click();
  await page.getByRole('button',{name:'Create Role',exact:true}).click();
  await page.getByLabel('Role template',{exact:true}).selectOption('publisher');
  await page.getByRole('button',{name:'Apply Template',exact:true}).click();
  await expect(page.getByLabel('ROLE NAME',{exact:true})).toHaveValue('Publisher');
  await expect(page.getByRole('checkbox',{name:'Publish Bulletins',exact:true})).toBeChecked();
  await expect(page.getByRole('checkbox',{name:'Administrator',exact:true})).not.toBeChecked();
  await page.getByLabel('ROLE NAME',{exact:true}).fill('News Team');
  await page.getByRole('button',{name:'Save as Template',exact:true}).click();
  await expect(page.getByRole('button',{name:'Delete template: News Team',exact:true})).toBeVisible();
  await page.getByLabel('Role template',{exact:true}).selectOption({label:'News Team'});
  await page.getByRole('button',{name:'Apply Template',exact:true}).click();
  await page.getByRole('button',{name:'Create Role',exact:true}).click();
  await expect(page.locator('.role-select').filter({hasText:'News Team'})).toBeVisible();
  const state=await (await page.request.get('/api/state')).json();
  const server=state.servers.find(s=>s.name==='Template Lab');
  const guest=await request.post('/api/auth/register',{data:{username:'template_guest',displayName:'Template Guest',password:'Fixture-password-482'}});
  expect(guest.status()).toBe(200);const guestId=(await guest.json()).me.id;
  expect((await request.post('/api/invites/join',{data:{code:server.invite}})).status()).toBe(200);
  await page.getByRole('button',{name:'Members',exact:true}).click();
  await page.getByRole('button',{name:'Manage roles for Template Guest',exact:true}).click();
  await page.getByRole('checkbox',{name:'News Team',exact:true}).check();
  const date=new Date(Date.now()+3600000);date.setSeconds(0,0);
  const local=new Date(date.getTime()-date.getTimezoneOffset()*60000).toISOString().slice(0,16);
  await page.getByLabel('Expires: News Team',{exact:true}).fill(local);
  await page.getByRole('button',{name:'Save Roles',exact:true}).click();
  const updated=await (await page.request.get('/api/state')).json();
  const savedServer=updated.servers.find(s=>s.id===server.id),news=savedServer.roles.find(r=>r.name==='News Team');
  expect(savedServer.roleExpirations[guestId][news.id]).toBe(date.getTime());
  for(const type of ['bulletin','links']){
    const r=await page.request.post('/api/servers/'+server.id+'/channels',{data:{name:'new-'+type,type}});
    expect(r.status()).toBe(201);
    expect((await r.json())[type]).toBe(true);
  }
});
